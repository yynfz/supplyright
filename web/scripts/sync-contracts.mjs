// Generates, from files outside web/:
//   src/generated/abis.ts             <- Foundry build output in ../contracts/out (run `forge build` first)
//   src/generated/wallets.sepolia.ts  <- public role-wallet addresses in ../config/wallets.sepolia.json
// Run:  npm run sync:contracts
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { getAddress } from "viem";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "../contracts/out");
const contracts = {
  supplyRightNftAbi: "SupplyRightNFT",
  protectionNftAbi: "ProtectionNFT",
  recoveryClaimNftAbi: "RecoveryClaimNFT",
  vaultAbi: "SupplyProtectionVault",
  claimManagerAbi: "SupplyClaimManager",
};

let ts = "// AUTO-GENERATED by scripts/sync-contracts.mjs from contracts/out. Do not edit.\n\n";
for (const [exportName, name] of Object.entries(contracts)) {
  const file = resolve(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run \`forge build\` in contracts/ first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  ts += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(root, "src/generated/abis.ts"), ts);
console.log("Wrote src/generated/abis.ts");

// Only an allow-listed set of public fields is copied; descriptions, RPC settings and anything else in the
// config never reach the bundle. Keystores live outside the repo and are never read here.
const ROLE_KEYS = ["admin", "buyer", "provider", "verifier"];
const walletsFile = resolve(root, "../config/wallets.sepolia.json");
const checksum = (value) => (typeof value === "string" && value ? getAddress(value) : null);
const text = (value, fallback) => (typeof value === "string" && value.trim() ? value.trim() : fallback);

let wallets = { chainId: 11155111, explorer: "https://sepolia.etherscan.io", deployer: null, roles: {} };
if (existsSync(walletsFile)) {
  const raw = JSON.parse(readFileSync(walletsFile, "utf8"));
  if (raw.chainId !== undefined && raw.chainId !== 11155111) throw new Error(`${walletsFile}: chainId must be 11155111.`);
  wallets = {
    chainId: 11155111,
    explorer: text(raw.explorer, wallets.explorer).replace(/\/+$/, ""),
    deployer: checksum(raw.deployer?.address),
    roles: {},
  };
  for (const key of ROLE_KEYS) {
    const w = raw.wallets?.[key] ?? {};
    wallets.roles[key] = { address: checksum(w.address), keystoreAlias: text(w.keystoreAlias, `supplyright-${key}`), label: text(w.role, key) };
  }
} else {
  console.warn(`No ${walletsFile}; writing empty Sepolia role wallets.`);
  for (const key of ROLE_KEYS) wallets.roles[key] = { address: null, keystoreAlias: `supplyright-${key}`, label: key };
}

const walletsTs = `// AUTO-GENERATED by scripts/sync-contracts.mjs from config/wallets.sepolia.json. Do not edit.
// Public data only. An alias says which wallet was set up for a role; authority always comes from onchain hasRole.

export type SepoliaRoleKey = ${ROLE_KEYS.map((k) => JSON.stringify(k)).join(" | ")};

export type SepoliaRoleWallet = {
  address: \`0x\${string}\` | null;
  keystoreAlias: string;
  label: string;
};

export const SEPOLIA_WALLETS: {
  chainId: 11155111;
  explorer: string;
  deployer: \`0x\${string}\` | null;
  roles: Record<SepoliaRoleKey, SepoliaRoleWallet>;
} = ${JSON.stringify(wallets, null, 2)};
`;
writeFileSync(resolve(root, "src/generated/wallets.sepolia.ts"), walletsTs);
console.log("Wrote src/generated/wallets.sepolia.ts");
