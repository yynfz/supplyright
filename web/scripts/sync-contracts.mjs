// Generates src/generated/abis.ts from the Foundry build output in ../contracts/out.
// Run after `forge build`:  npm run sync:contracts
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "../contracts/out");
const contracts = {
  supplyRightNftAbi: "SupplyRightNFT",
  protectionNftAbi: "ProtectionNFT",
  recoveryClaimNftAbi: "RecoveryClaimNFT",
  vaultAbi: "SupplyProtectionVault",
  claimManagerAbi: "SupplyClaimManager",
  mockEthAbi: "MockETH",
};

let ts = "// AUTO-GENERATED by scripts/sync-contracts.mjs from contracts/out. Do not edit.\n\n";
for (const [exportName, name] of Object.entries(contracts)) {
  const file = resolve(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run \`forge build\` in contracts/ first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  ts += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(root, "src/generated/abis.ts"), ts);
console.log("Wrote src/generated/abis.ts");
